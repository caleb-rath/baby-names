import re, json, csv, unicodedata, sys
from collections import defaultdict
sys.path.insert(0, '.')
from extra import EXTRA
from tags import add_tags
SRC = sys.argv[1]; SSA = sys.argv[2]; OUT = sys.argv[3]
lines = open(SRC, encoding='utf-8').read().split('\n')
row_re = re.compile(r"^\s*\['((?:[^'\\]|\\.)*)','([MFN])','((?:[^'\\]|\\.)*)','((?:[^'\\]|\\.)*)',(\d+),(\d+),(true|false)\]")
FILLER_BLOCKS = [(334, 364), (1807, 1857)]
rows = []
for i, l in enumerate(lines, 1):
    m = row_re.match(l)
    if m:
        n, g, o, me, syl, _, _ = m.groups()
        rows.append(dict(name=n.replace("\\'", "'"), gender=g, origin=o.replace("\\'", "'"), meaning=me.replace("\\'", "'"), syl=int(syl),
                         filler=any(a <= i <= b for a, b in FILLER_BLOCKS)))
print('rows', len(rows))
counts = defaultdict(lambda: {'F': 0, 'M': 0})
for r in csv.DictReader(open(f'{SSA}/recent.csv')):
    counts[r['name']][r['sex']] += int(r['n'])
rank = {}
for g, f in (('M', 'boy'), ('F', 'girl')):
    for i, n in enumerate(json.load(open(f'{SSA}/{f}_2024.json'))['names'], 1):
        rank.setdefault(n, {})[g] = i

def slug(n):
    return ''.join(c for c in unicodedata.normalize('NFKD', n.lower()) if c.isalnum())

OVERRIDE = {'Yael': 'F', 'Joan': 'F', 'Kani': 'F', 'Quinn': 'N', 'Emery': 'N', 'Rowan': 'N'}
def ssa_gender(n, fallback):
    if n in OVERRIDE: return OVERRIDE[n]
    c = counts.get(n)
    if not c: return fallback
    tot = c['F'] + c['M']
    if tot < 200: return fallback
    share = max(c['F'], c['M']) / tot
    if share <= (0.95 if fallback == 'N' else 0.65): return 'N'
    return 'F' if c['F'] > c['M'] else 'M'

def syllables(n):
    s = re.sub(r'e$', '', n.lower())
    return max(1, len(re.findall(r'[aeiouyàáéíóú]+', s)))

out = {}
dropped = []
for r in rows:
    k = slug(r['name'])
    if r['filler']:
        c = counts.get(r['name'], {'F': 0, 'M': 0})
        if c['F'] + c['M'] < 300:
            dropped.append(r['name']); continue
    if k in out:
        if len(r['meaning']) > len(out[k]['meaning']): out[k]['meaning'] = r['meaning']
        continue
    out[k] = dict(name=r['name'], gender=r['gender'], origin=r['origin'], meaning=r['meaning'], syl=r['syl'])
for n, g, o, me in EXTRA:
    k = slug(n)
    if k in out:
        if g: out[k]['gender'] = g
        continue
    out[k] = dict(name=n, gender=g or 'N', origin=o, meaning=me, syl=syllables(n))
regendered = []
for k, v in out.items():
    ng = ssa_gender(v['name'], v['gender'])
    if ng != v['gender']: regendered.append(f"{v['name']}:{v['gender']}>{ng}")
    v['gender'] = ng
    rk = rank.get(v['name'], {})
    if ng == 'N': r_ = min(rk.values()) if rk else 0
    else: r_ = rk.get(ng, 0)
    v['rank'] = r_
add_tags(out, SSA)
print('unique', len(out), 'dropped', len(dropped), dropped)
print('regendered', len(regendered), regendered[:80])
from collections import Counter
print(Counter(v['gender'] for v in out.values()), Counter(v['origin'] for v in out.values() if v['origin'] in ('Sanskrit','Tamil')))
def q(s): return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
groups = sorted({v['group'] for v in out.values()})
gi = {g: i for i, g in enumerate(groups)}
body = ',\n'.join(f"  [{q(v['name'])},'{v['gender']}',{q(v['origin'])},{gi[v['group']]},{q(v['meaning'])},{v['syl']},{v['rank']},'{v['tags']}']" for v in sorted(out.values(), key=lambda v: v['name']))
grp_ts = ', '.join(q(g) for g in groups)
ts = f"""import type {{ BabyName, Gender }} from '../types';

// Generated by tools/build-names.py. One row per name; ids are slugs of the name so they stay stable when rows are added.
// rank = 2024 US SSA rank (0 = outside the top 1000). Gender from US births 2010-2017: N when neither sex is above 65%
// (95% for names curated as unisex). Tags: c = family classic (peaked 1905-1965), r = rising since 2015, n = nature, v = virtue.
type R = [string, Gender, string, number, string, number, number, string];

export const ORIGIN_GROUPS = [{grp_ts}] as const;

const RAW: R[] = [
{body},
];

export function nameSlug(name: string): string {{
  return name.normalize('NFKD').toLowerCase().replace(/[^a-z0-9]/g, '');
}}

export const BABY_NAMES: BabyName[] = RAW.map(([name, gender, origin, group, meaning, syllables, rank, tags]) => ({{
  id: nameSlug(name),
  name,
  gender,
  origin,
  group: ORIGIN_GROUPS[group],
  meaning,
  syllables,
  rank,
  tags,
}}));

export const NAMES_BY_ID: Record<string, BabyName> = Object.fromEntries(BABY_NAMES.map((n) => [n.id, n]));
"""
open(OUT, 'w', encoding='utf-8').write(ts)
